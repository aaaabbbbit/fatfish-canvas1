/**
 * fatfish-canvas 构建脚本 —— 零原生依赖。
 *
 * 为什么不用 esbuild：本机上 esbuild 的原生二进制（esbuild.exe）所在的包目录
 * 会被反复的 rename 卡死（EPERM）—— pnpm 在该卷上的原子目录重命名存在竞态。
 * 改用 **纯 JS 的 TypeScript 编译器 API**，配合一个约 50 行的内部模块注册表，
 * 构建过程完全确定、可离线、无原生二进制。
 *
 * 产出两个半边：
 *
 *   lib/index.js   宿主半边 —— Node ESM。宿主源码只有类型导入，转译后没有任何
 *                  运行时 import，因此无需打包。
 *
 *   lib/client.js  浏览器半边 —— DSH 惰性 CJS 模块契约：
 *
 *     window.__ModuleLoader__.load({ id, factory: (require) => { …; return module.exports; } });
 *
 *   脚本执行时**只注册 factory**（不得有副作用）；模块体（含 CSS 注入）在
 *   factory 被物化时才运行。factory 拿到的同步 `require` 只解析「统一基座」
 *   里的词条 —— 已在本机前端产物中逐字核实为以下 7 个精确 specifier：
 *
 *     react | react/jsx-runtime | react-dom | react-dom/client
 *     @deepseek-ai/cordis | @deepseek-ai/dsh-client-ui-slots
 *     @deepseek-ai/dsh-client-ui-primitives
 *
 *   其余一切必须内联打包，或经 package.json 的 `dsh.client.external` 登记。
 *   本插件只用基座，因此无需 external。
 */

import ts from 'typescript';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));

const PLUGIN_ID = pkg.name;
const HOST_SRC = resolve(root, 'src');
const CLIENT_SRC = resolve(root, 'src/client');
const CLIENT_ENTRY = resolve(CLIENT_SRC, 'index.tsx');
const HOST_ENTRY = resolve(root, 'src/index.ts');
const OUT_DIR = resolve(root, 'lib');

/** 外壳播种的统一基座：factory 的同步 require 只能解析这些词条。 */
const BASE_MODULES = new Set([
	'react',
	'react/jsx-runtime',
	'react-dom',
	'react-dom/client',
	'@deepseek-ai/cordis',
	'@deepseek-ai/dsh-client-ui-slots',
	'@deepseek-ai/dsh-client-ui-primitives',
]);

/** 统一基座之外、经 `dsh.client.external` 登记的额外请求。 */
const EXTRA_EXTERNALS = new Set(pkg.dsh?.client?.external ?? []);

const banner = (suffix) =>
	`// ${PLUGIN_ID}${suffix}: generated by build.mjs (TypeScript API). Do not edit directly.`;

// ─────────────────────────── 共用 ───────────────────────────

const BASE_COMPILER_OPTIONS = {
	target: ts.ScriptTarget.ES2022,
	module: ts.ModuleKind.CommonJS,
	jsx: ts.JsxEmit.ReactJSX,
	esModuleInterop: true,
	removeComments: false,
	newLine: ts.NewLineKind.LineFeed,
};

/**
 * 转译单个源码文件。
 * @param source - 源码文本。
 * @param fileName - 用于诊断的文件名。
 * @param overrides - 覆盖的编译选项。
 * @returns 转译后的 JS 文本。
 */
function transpile(source, fileName, overrides = {}) {
	const result = ts.transpileModule(source, {
		compilerOptions: { ...BASE_COMPILER_OPTIONS, ...overrides },
		fileName,
		reportDiagnostics: true,
	});
	const errors = (result.diagnostics ?? []).filter(
		(d) => d.category === ts.DiagnosticCategory.Error,
	);
	if (errors.length > 0) {
		const text = errors
			.map((d) => ts.flattenDiagnosticMessageText(d.messageText, ' '))
			.join('\n  ');
		throw new Error(`build.mjs: 转译 ${fileName} 失败：\n  ${text}`);
	}
	return result.outputText;
}

// ─────────────────────────── 宿主半边 ───────────────────────────

/**
 * 收集宿主半边的模块图（只跟随相对 import；裸 specifier 交给 node_modules）。
 *
 * 宿主半边**不打包**：Node ESM 原生支持多文件，打包只会让堆栈与调试变难。
 * 因此按模块图把每个源文件镜像到 `lib/` 下的同名位置。
 * @param entry - 入口绝对路径。
 * @returns 模块 id → `{ source, absPath }`。
 */
async function collectHostGraph(entry) {
	const modules = new Map();
	const visiting = new Set();

	async function visit(id, absPath, chain) {
		if (modules.has(id)) return;
		if (visiting.has(id)) {
			throw new Error(`build.mjs: 宿主半边检测到 import 环：${[...chain, id].join(' -> ')}`);
		}
		visiting.add(id);
		const source = await readFile(absPath, 'utf8');
		modules.set(id, { source, absPath });

		for (const match of source.matchAll(IMPORT_RE)) {
			const spec = match[1];
			if (spec === undefined || !spec.startsWith('.')) continue;
			const childId = resolveId(id, spec);
			let found = false;
			for (const ext of ['.ts', '.tsx', '.js', '.mjs']) {
				const candidate = resolve(HOST_SRC, `${childId}${ext}`);
				try {
					await readFile(candidate, 'utf8');
				} catch {
					continue;
				}
				await visit(childId, candidate, [...chain, id]);
				found = true;
				break;
			}
			if (!found) throw new Error(`build.mjs: ${absPath} 的 "${spec}" 解析不到源文件`);
		}
		visiting.delete(id);
	}

	await visit(moduleIdOf(entry, HOST_SRC), entry, []);
	return modules;
}

/**
 * 给相对 specifier 补上显式扩展名。
 *
 * Node ESM 不做扩展名补全，而 TypeScript 源码里写的是无扩展名的相对导入；
 * 转译后原样保留会直接 ERR_MODULE_NOT_FOUND。这是宿主半边唯一的产物改写。
 * @param js - 转译后的 JS。
 * @returns 改写后的 JS。
 */
function addJsExtensions(js) {
	return js.replace(
		/(\bfrom\s*)(['"])(\.[^'"]+)\2|(\bimport\s*\(\s*)(['"])(\.[^'"]+)\5/g,
		(match, fromKw, fromQ, fromSpec, impKw, impQ, impSpec) => {
			if (typeof fromSpec === 'string') {
				return /\.(js|mjs|cjs|json)$/.test(fromSpec)
					? match
					: `${fromKw}${fromQ}${fromSpec}.js${fromQ}`;
			}
			if (typeof impSpec === 'string') {
				return /\.(js|mjs|cjs|json)$/.test(impSpec)
					? match
					: `${impKw}${impQ}${impSpec}.js${impQ}`;
			}
			return match;
		},
	);
}

async function buildHost() {
	const graph = await collectHostGraph(HOST_ENTRY);
	const entryId = moduleIdOf(HOST_ENTRY, HOST_SRC);

	for (const [id, { source, absPath }] of graph) {
		const js = addJsExtensions(
			transpile(source, relative(root, absPath), {
				module: ts.ModuleKind.ESNext,
				verbatimModuleSyntax: true,
			}),
		);
		const outPath = resolve(OUT_DIR, `${id}.js`);
		await mkdir(dirname(outPath), { recursive: true });
		await writeFile(outPath, `${banner(` (host: ${id})`)}\n${js}`, 'utf8');
	}
	console.log(
		`[${PLUGIN_ID}] host half   -> lib/${entryId}.js (${String(graph.size)} modules: ${[...graph.keys()].join(', ')})`,
	);
}

// ─────────────────────────── 客户端半边 ───────────────────────────

/** 匹配运行时会保留的静态 import（负向先行断言跳过 `import type …`）。 */
const IMPORT_RE = /\bimport\s+(?!type\b)(?:[^'"]*?\s+from\s*)?['"]([^'"]+)['"]/g;

/**
 * 扩展名无关的模块 id：相对源码根的路径去掉扩展名。
 * @param absPath - 绝对路径。
 * @param srcRoot - 源码根（客户端为 `src/client`，宿主为 `src`）。
 * @returns 模块 id（如 `index`、`host/schema`）。
 */
function moduleIdOf(absPath, srcRoot = CLIENT_SRC) {
	return relative(srcRoot, absPath)
		.replace(/\\/g, '/')
		.replace(/\.(tsx?|jsx?|mjs?)$/, '');
}

/**
 * 解析相对 specifier 为模块 id（与运行时 `__ffcResolve` 同一算法）。
 * @param fromId - 发起 import 的模块 id。
 * @param spec - specifier。
 * @returns 模块 id。
 */
function resolveId(fromId, spec) {
	const base = fromId.includes('/') ? fromId.slice(0, fromId.lastIndexOf('/')) : '';
	const parts = (base === '' ? spec : `${base}/${spec}`).split('/');
	const out = [];
	for (const part of parts) {
		if (part === '' || part === '.') continue;
		if (part === '..') out.pop();
		else out.push(part);
	}
	return out.join('/');
}

/**
 * 收集 `src/client` 下的模块图。
 *
 * 只跟随**相对** import；裸 specifier 必须落在统一基座或 external 白名单内，
 * 否则构建期直接失败（而不是等到浏览器里 require 抛错）。顺带做环检测 ——
 * DSH 的模块 loader 在 require 环上会抛错，构建期失败远比线上失败好。
 * @returns 模块 id → 源码文本，按发现顺序。
 */
async function collectClientGraph() {
	const modules = new Map();
	const visiting = new Set();

	async function visit(id, absPath, chain) {
		if (modules.has(id)) return;
		if (visiting.has(id)) {
			throw new Error(
				`build.mjs: 检测到 require 环，DSH 的模块 loader 会在物化时抛错：\n  ${[...chain, id].join(' -> ')}`,
			);
		}
		visiting.add(id);
		const source = await readFile(absPath, 'utf8');
		modules.set(id, { source, absPath });

		for (const match of source.matchAll(IMPORT_RE)) {
			const spec = match[1];
			if (spec === undefined) continue;
			if (!spec.startsWith('.')) {
				if (!BASE_MODULES.has(spec) && !EXTRA_EXTERNALS.has(spec)) {
					throw new Error(
						`build.mjs: ${absPath} 引入了 "${spec}"，它既不在统一基座内，` +
							`也未登记到 package.json 的 dsh.client.external。\n` +
							`  基座可用：${[...BASE_MODULES].join(', ')}`,
					);
				}
				continue;
			}
			const childId = resolveId(id, spec);
			let found = false;
			for (const ext of ['.tsx', '.ts', '.jsx', '.js']) {
				const candidate = resolve(CLIENT_SRC, `${childId}${ext}`);
				try {
					await readFile(candidate, 'utf8');
				} catch {
					continue;
				}
				await visit(childId, candidate, [...chain, id]);
				found = true;
				break;
			}
			if (!found) {
				throw new Error(`build.mjs: ${absPath} 的 "${spec}" 解析不到任何源文件`);
			}
		}

		visiting.delete(id);
	}

	await visit(moduleIdOf(CLIENT_ENTRY), CLIENT_ENTRY, []);
	return modules;
}

/** 运行时内部模块注册表（产物的一部分；刻意写成 ES5 风格以最大化兼容）。 */
const RUNTIME = `
var __ffcMods = {};
var __ffcCache = {};
function __ffcDefine(id, fn) { __ffcMods[id] = fn; }
function __ffcResolve(fromId, spec) {
	var i = fromId.lastIndexOf('/');
	var base = i === -1 ? '' : fromId.slice(0, i);
	var parts = (base === '' ? spec : base + '/' + spec).split('/');
	var out = [];
	for (var j = 0; j < parts.length; j++) {
		if (parts[j] === '' || parts[j] === '.') continue;
		if (parts[j] === '..') { out.pop(); continue; }
		out.push(parts[j]);
	}
	return out.join('/');
}
function __ffcLoad(id) {
	var hit = __ffcCache[id];
	if (hit !== undefined) return hit.exports;
	var fn = __ffcMods[id];
	if (fn === undefined) throw new Error(${JSON.stringify(`${PLUGIN_ID}: internal module not found: `)} + id);
	var mod = { exports: {} };
	__ffcCache[id] = mod;
	fn(mod, mod.exports, function (spec) {
		return spec.charAt(0) === '.' ? __ffcLoad(__ffcResolve(id, spec)) : require(spec);
	});
	return mod.exports;
}
`.trim();

async function buildClient() {
	const graph = await collectClientGraph();
	const entryId = moduleIdOf(CLIENT_ENTRY);

	const parts = [RUNTIME];
	for (const [id, { source, absPath }] of graph) {
		const js = transpile(source, relative(root, absPath));
		parts.push(
			`__ffcDefine(${JSON.stringify(id)}, function (module, exports, require) {\n${js}\n});`,
		);
	}
	parts.push(`return __ffcLoad(${JSON.stringify(entryId)});`);

	const wrapped = [
		banner(' (client)'),
		`window.__ModuleLoader__.load({`,
		`\tid: ${JSON.stringify(PLUGIN_ID)},`,
		`\tfactory: (require) => {`,
		parts.join('\n\n'),
		`\t}`,
		`});`,
		``,
	].join('\n');

	await mkdir(OUT_DIR, { recursive: true });
	await writeFile(resolve(OUT_DIR, 'client.js'), wrapped, 'utf8');
	console.log(
		`[${PLUGIN_ID}] client half -> lib/client.js (${String(wrapped.length)} bytes, ${String(graph.size)} modules: ${[...graph.keys()].join(', ')})`,
	);
}

// ─────────────────────────── 入口 ───────────────────────────

await buildHost();
await buildClient();
